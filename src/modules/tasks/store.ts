/**
 * @module
 * Pinia store for the tasks module: a public submit action plus the admin's inbox, built on
 * `useStructureCrudApi` the same way users, products and orders are — server-paginated search,
 * a status update, a delete.
 */
import { defineStore } from 'pinia';
import { ref } from 'vue';
import { useStructureCrudApi } from '@guebbit/vue-toolkit';
import type { AxiosRequestConfig } from 'axios';
import { useIdempotencyKey } from '@/infrastructure/http/idempotency.ts';
import { asPassive } from '@/infrastructure/http/passive.ts';
import { queryClient } from '@/infrastructure/query-client.ts';
import { sortTokensOf } from '@/infrastructure/utils/sort.ts';
import {
    assignTask,
    createContactTask,
    createTaskNote,
    deleteTask,
    getTask,
    getTaskSummary,
    markTaskSpam,
    reopenTask,
    resolveTask,
    searchTasks,
    unassignTask,
    TaskSortItem
} from '@api';
import type { CreateContactTaskRequest, Task, SearchTasksRequest, TaskSummary } from '@types';

/**
 * Search criteria for the inbox, i.e. everything but pagination (which is owned by the toolkit's
 * search state).
 */
type TaskFilters = Omit<SearchTasksRequest, 'page' | 'pageSize' | 'sort'> & {
    /** The API's `sort` as one CSV (`-createdAt`): the form a URL holds. */
    sort?: string;
};

/**
 * The contact form's two audiences: anyone may submit, staff read the inbox and work tasks
 * through the status doors.
 *
 * See the products store for the shape — the inbox is declared as a resource like every other
 * admin list, so paging and caching behave the same everywhere.
 */
export const useTasksStore = defineStore('tasks', () => {
    /**
     * Record cache, list/pagination state and the inbox's actions, generated by the toolkit's
     * structured-CRUD primitive. No `list`/`get`/`create`: the inbox is only ever read as a
     * search page, and the public submit is not an inbox record (see {@link submitContact}).
     *
     * `search:` is `POST /tasks/search`, never `GET /tasks`: the filters and the page travel
     * in a body, and a POST is never browser-cached, so a reload cannot hand back a row just deleted.
     */
    const {
        itemDictionary: requests,
        itemList: requestsList,

        filters,
        loading,
        pageCurrent,
        pageSize,
        pageTotal,
        pageItemList,

        fetchPage: fetchPaginationRequests,
        watchList: watchSearchRequests,
        deleteOne: deleteRequest,
        fetchAny
    } = useStructureCrudApi<Task, string, TaskFilters>(
        {
            search: (filters, page, pageSize) =>
                searchTasks({
                    page,
                    pageSize,
                    text: filters.text,
                    sort: sortTokensOf(filters.sort, TaskSortItem),
                    status: filters.status,
                    category: filters.category,
                    source: filters.source,
                    kind: filters.kind,
                    assignee: filters.assignee,
                    overdue: filters.overdue,
                    email: filters.email
                }).then((response) => ({
                    items: response.items,
                    totalItems: response.meta.totalItems
                })),

            remove: (requestId) => deleteTask(requestId)
        },
        { resourceKey: 'tasks', queryClient }
    );

    /**
     * The task the detail page shows. Every door answers the task as it now stands, so the page
     * swaps this in and never re-reads.
     */
    const task = ref<Task>();

    /**
     * The staff badge's counts: open, mine, overdue and unassigned, inside the caller's jurisdiction.
     */
    const summary = ref<TaskSummary>();

    /**
     * Keeps the answer of a door as the current task.
     *
     * @param next - The task as the server now holds it.
     * @returns The same task.
     */
    const keep = (next: Task): Task => {
        task.value = next;
        return next;
    };

    /**
     * Reads one task for the detail page: notes, assignee and the earlier tasks on the same record.
     *
     * @param id - Which task.
     */
    const loadTask = (id: string) => getTask(id).then(keep);

    /**
     * Reads the badge's counts. Passive: the app asks, not the person, so it must not keep a staff
     * session from idling out.
     */
    const loadSummary = () =>
        getTaskSummary(asPassive()).then((counts) => {
            summary.value = counts;
            return counts;
        });

    /**
     * The status doors and the staff thread. Each answers the task after the move; which ones
     * are offered is the task's own `actions`, never recomputed here.
     */
    const resolve = (id: string) => resolveTask(id).then(keep);
    const markSpam = (id: string) => markTaskSpam(id).then(keep);
    const reopen = (id: string) => reopenTask(id).then(keep);
    const assign = (id: string, userId: string) => assignTask(id, { userId }).then(keep);
    const unassign = (id: string) => unassignTask(id).then(keep);
    const addNote = (id: string, body: string) => createTaskNote(id, { body }).then(keep);

    /**
     * `Idempotency-Key` for `submitContact` — a network error or a 5xx resends the SAME
     * key, so a lost response never sends the message twice; any other outcome mints a fresh one.
     */
    const contactIdempotencyKey = useIdempotencyKey();

    /**
     * Submits the public contact form. Through `fetchAny`, not `createOne`: the visitor never
     * reads the inbox, so there is nothing to cache the created task into.
     *
     * @param message - Name (optional), email, subject and message.
     * @param options - Per-call axios overrides, forwarded to `orvalMutator` — `Contact.vue`
     *  attaches a solved `HumanCheck` token through it: this route is always guarded by
     *  `humanChallengeGate` once a provider is active.
     * @returns A promise resolving once the API accepts it.
     */
    const submitContact = (message: CreateContactTaskRequest, options?: AxiosRequestConfig) =>
        fetchAny(() =>
            createContactTask(message, contactIdempotencyKey.withKey(options))
                .then((response) => {
                    contactIdempotencyKey.settle();
                    return response;
                })
                .catch((error: unknown) => {
                    contactIdempotencyKey.settle(error);
                    throw error;
                })
        );

    return {
        requests,
        requestsList,

        filters,
        loading,
        pageCurrent,
        pageSize,
        pageTotal,
        pageItemList,

        task,
        summary,

        submitContact,
        fetchPaginationRequests,
        watchSearchRequests,
        deleteRequest,
        loadTask,
        loadSummary,
        resolve,
        markSpam,
        reopen,
        assign,
        unassign,
        addNote
    };
});
