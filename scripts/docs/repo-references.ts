/**
 * @module
 * Whether a path cited in prose or in a comment still exists in this repo — the machinery shared
 * by `check-references.ts` (every `docs/*.md` page) and `local/comment-links` (every `.ts`
 * comment), so the two agree on what counts as a real path.
 *
 * The callers differ on purpose: a page resolves `./relative` against VitePress and a paired-repo
 * token against the peer checkout, neither of which a source comment does. Those policies stay
 * with each caller, on top of the primitives here.
 */

